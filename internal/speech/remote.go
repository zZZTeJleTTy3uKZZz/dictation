// Настройки своего провайдера из voice.json — одним местом.
//
// ЗАЧЕМ. Значок, ядро (cmd/core) и ядро настроек собирают «сервис по сети» из
// одних и тех же полей voice.json. Пока сборка жила в трёх копиях, они успели
// разойтись: у одной не было языка, у другой — ключа. Здесь она одна, и её же
// берёт служба диктовки.
package speech

import (
	"github.com/zZZTeJleTTy3uKZZz/dictation/internal/prefs"
)

// RemoteFromVoice — «сервис по сети» по настройкам человека.
//
// Ключ берётся по адресу из хранилища, а не из voice.json, и его хозяин — узел
// адреса: ключ нашего роутера не уходит чужому сервису, ключ чужого не уходит
// роутеру, а со сменой адреса прежний ключ новому сервису не достаётся.
//
// Открытое поле voice.SpeechKey здесь не участвует: это прежнее место ключа, и
// оно живёт лишь ради переноса в хранилище (secrets.go). Открытый ключ не
// станет приоритетнее зашифрованного, даже если перенос ещё не дошёл.
//
// Пустой адрес — способ не собран: идти некуда, и Ready об этом скажет.
func RemoteFromVoice(voice *prefs.Voice) Remote {
	if voice == nil {
		return Remote{}
	}
	return Remote{
		URL:      voice.SpeechURL,
		Key:      KeyForURL("", voice.SpeechURL).Key,
		Model:    voice.SpeechModel,
		Language: voice.SpeechLanguage,
	}
}
