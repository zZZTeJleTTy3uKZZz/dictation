// Package ui — страницы окон клиента.
//
// ПОЧЕМУ HTML, А НЕ НАСТОЯЩИЕ ОКНА. На Go нет библиотеки окон, которая на
// Windows выглядела бы прилично и не тащила бы за собой половину Qt. Зато в
// самой Windows уже стоит движок браузера (WebView2, тот же, что в Edge): окно
// получается из HTML, а вся логика остаётся в Go — страница только показывает и
// зовёт по имени.
//
// Страницы лежат отдельными файлами, а не строками в коде: их правят как
// разметку, с подсветкой и переносами, и путать их с логикой незачем.
package ui

import "embed"

//go:embed pages/*.html
var pages embed.FS

// Page — разметка окна по имени: "settings" или "ask".
func Page(name string) string {
	raw, err := pages.ReadFile("pages/" + name + ".html")
	if err != nil {
		// Файл вшит в программу на сборке: если его нет, собрали неправильно, и
		// пустое окно скажет об этом громче тихой подмены.
		return "<p>страница " + name + " не собрана</p>"
	}
	return string(raw)
}
