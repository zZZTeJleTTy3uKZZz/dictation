// noterestore — вернуть историю заметок из уцелевших записей.
//
// Зачем отдельная программа. Тексты заметок живут только в истории, и если
// история потеряна, звук остаётся единственным, что помнит сказанное. Записи
// диктовки лежат в папке службы, названы своим временем — значит историю можно
// собрать заново: время из имени, звук на место, текст расшифровкой.
//
// Пишет в ОТДЕЛЬНЫЙ файл, а не в живую историю. Пока человек не посмотрел
// список, трогать живую нельзя: ошибку в инструменте он не заметит, а история
// у него одна.
//
//	noterestore <папка с записями> <куда писать> [сколько записей] [модель]
//
// Ключ Groq берётся из настроек, как и всегда: ни в вывод, ни в журналы он не
// попадает. Прогон можно прервать и запустить снова — уже записанное
// пропускается.
package main

import (
	"bufio"
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/zZZTeJleTTy3uKZZz/dictation/internal/notes"
	"github.com/zZZTeJleTTy3uKZZz/dictation/internal/speech"
)

// пробаРазмер — размер моих пробных копий от замеров сжатия. Это не диктовки
// человека, и расшифровывать их незачем.
const пробаРазмер = 443879

// байтВСекунду — грубая мера для mp3 диктовки: по ней выходит длительность,
// когда точной неоткуда взять. Замер: 443 879 б — 147,7 с.
const байтВСекунду = 3000

func main() {
	if len(os.Args) < 3 {
		fmt.Println("нужно: noterestore <папка с записями> <куда писать> [сколько записей] [модель]")
		os.Exit(1)
	}
	откуда, куда := os.Args[1], os.Args[2]
	предел := 0
	if len(os.Args) > 3 {
		предел, _ = strconv.Atoi(os.Args[3])
	}

	записи, err := записиИз(откуда)
	if err != nil {
		fmt.Println("не прочитать записи:", err)
		os.Exit(1)
	}
	готовые, err := ужеГотовые(куда)
	if err != nil {
		fmt.Println("не прочитать сделанное:", err)
		os.Exit(1)
	}

	ожидают := 0
	for _, путь := range записи {
		if !готовые[номерИз(путь)] {
			ожидают++
		}
	}
	fmt.Printf("записей %d, уже сделано %d, осталось %d\n", len(записи), len(готовые), ожидают)
	if предел > 0 && ожидают > предел {
		ожидают = предел
	}

	// Модель — первый довод конструктора распознавания. Пустая строка означала
	// «взять по умолчанию», то есть whisper-large-v3 с пределом двадцать
	// запросов в минуту: на восьмидесяти пяти записях это упирается в отказы.
	// Турбо и быстрее — 0,8 с против 1,95 с на одной и той же записи, — и свои
	// запросы считает отдельно.
	модель := "whisper-large-v3-turbo"
	if len(os.Args) > 4 && os.Args[4] != "" {
		модель = os.Args[4]
	}
	// История — журнал дописыванием: прогон можно прервать на любом месте.
	store := notes.NewStore(куда)
	channel := speech.NewGroq(модель, "ru")
	сделано := 0
	for _, путь := range записи {
		if предел > 0 && сделано >= предел {
			break
		}
		номер := номерИз(путь)
		if готовые[номер] {
			continue
		}
		// Двадцать запросов в минуту — предел службы, и упереться в него значит
		// получить отказы вместо текста. Ровный шаг лучше быстрого в отказ.
		time.Sleep(3100 * time.Millisecond)
		began := time.Now()
		text, err := channel.Text(context.Background(), путь)
		if err != nil {
			fmt.Printf("%s: расшифровка не удалась: %v\n", filepath.Base(путь), err)
			continue
		}
		когда, err := времяИз(номер)
		if err != nil {
			fmt.Printf("%s: не разобрать время: %v\n", filepath.Base(путь), err)
			continue
		}
		инфо, _ := os.Stat(путь)
		секунд := 0.0
		if инфо != nil {
			секунд = float64(инфо.Size()) / байтВСекунду
		}
		заметка := notes.Note{
			ID:      номер,
			At:      когда,
			Seconds: секунд,
			Audio:   путь,
			Text:    text,
			Source:  notes.SourceWidget,
		}
		if err := store.Add(заметка); err != nil {
			fmt.Printf("%s: не записать: %v\n", filepath.Base(путь), err)
			continue
		}
		сделано++
		fmt.Printf("%d/%d %s: %.1f с, знаков %d\n", сделано, ожидают, номер, time.Since(began).Seconds(), len([]rune(text)))
	}
	fmt.Printf("готово, записей добавлено: %d\n", сделано)
	if сделано > 0 {
		fmt.Println("смотри и решай: в живую историю ничего не переносилось")
	}
}

// записиИз — записи диктовки по времени, без моих пробных копий.
func записиИз(папка string) ([]string, error) {
	найдено, err := os.ReadDir(папка)
	if err != nil {
		return nil, err
	}
	пути := make([]string, 0, len(найдено))
	for _, запись := range найдено {
		if запись.IsDir() || !strings.Contains(запись.Name(), "speech") {
			continue
		}
		инфо, err := запись.Info()
		if err != nil || инфо.Size() == пробаРазмер {
			continue
		}
		пути = append(пути, filepath.Join(папка, запись.Name()))
	}
	sort.Strings(пути)
	return пути, nil
}

// ужеГотовые — номера, которые уже лежат в выходном файле: по ним прогон
// продолжается, а не начинается заново.
func ужеГотовые(путь string) (map[string]bool, error) {
	готовые := map[string]bool{}
	файл, err := os.Open(путь)
	if err != nil {
		if os.IsNotExist(err) {
			return готовые, nil
		}
		return nil, err
	}
	defer файл.Close()
	чтец := bufio.NewScanner(файл)
	чтец.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)
	for чтец.Scan() {
		var запись struct {
			ID string `json:"id"`
		}
		if err := json.Unmarshal(чтец.Bytes(), &запись); err == nil && запись.ID != "" {
			готовые[запись.ID] = true
		}
	}
	return готовые, чтец.Err()
}

// номерИз — номер заметки из имени записи: «20261014-025653-c30452-speech.mp3»
// даёт «20261014-025653.000». Доли секунды в имени не хранятся, и выдумывать их
// незачем: время и порядок от них не зависят.
func номерИз(путь string) string {
	имя := strings.TrimSuffix(filepath.Base(путь), filepath.Ext(путь))
	части := strings.Split(имя, "-")
	if len(части) < 2 || len(части[0]) != 8 || len(части[1]) != 6 {
		return имя
	}
	return части[0] + "-" + части[1] + ".000"
}

// времяИз — время заметки из её номера.
func времяИз(номер string) (time.Time, error) {
	return time.ParseInLocation("20060102-150405.000", номер, time.Local)
}
